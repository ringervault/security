"""Builds lib/utils/eff_words.g.dart and extension/src/vault/eff_words.js
from tool/eff_large_wordlist.txt.

The word list is the EFF Large Wordlist for Passphrases, by the Electronic
Frontier Foundation (https://www.eff.org/dice), licensed CC BY 3.0 US. Its
SHA-256 is checked so a changed file is noticed.

Run: python3 tool/gen_eff_words.py
"""
import hashlib
import re
import sys
from pathlib import Path

EXPECTED_SHA256 = 'addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e'
root = Path(__file__).resolve().parent.parent
source = root / 'tool' / 'eff_large_wordlist.txt'
data = source.read_bytes()
if hashlib.sha256(data).hexdigest() != EXPECTED_SHA256:
    sys.exit('eff_large_wordlist.txt is not the expected file')

words = []
for line in data.decode('utf-8').splitlines():
    match = re.fullmatch(r'([1-6]{5})\t([a-z]+(?:-[a-z]+)?)', line)
    if not match:
        sys.exit(f'unexpected line: {line!r}')
    words.append(match.group(2))
if len(words) != 7776 or len(set(words)) != 7776:
    sys.exit('expected 7776 distinct words')

body = ',\n'.join(f'  {w!r}'.replace("'", '"') for w in words)
(root / 'lib' / 'utils' / 'eff_words.g.dart').write_text(
    '// Generated by tool/gen_eff_words.py from tool/eff_large_wordlist.txt. Do not edit.\n'
    '//\n'
    '// The EFF Large Wordlist for Passphrases, by the Electronic Frontier\n'
    '// Foundation (https://www.eff.org/dice), licensed CC BY 3.0 US.\n\n'
    '/// 7,776 words: each picked at random adds about 12.9 bits.\n'
    'const List<String> effWords = [\n' + body + ',\n];\n'
)
js_body = ',\n'.join(f"  '{w}'" for w in words)
(root / 'extension' / 'src' / 'vault' / 'eff_words.js').write_text(
    '// Generated by tool/gen_eff_words.py from tool/eff_large_wordlist.txt. Do not edit.\n'
    '//\n'
    '// The EFF Large Wordlist for Passphrases, by the Electronic Frontier\n'
    '// Foundation (https://www.eff.org/dice), licensed CC BY 3.0 US.\n\n'
    'export const effWords = [\n' + js_body + ',\n];\n'
)
print('wrote', len(words), 'words')
